# improting math module or library
import math

# absolute value
print(math.fabs(-7.25))
print(math.fabs(7.25))

#square root
print(math.sqrt(49))

# power
print(math.pow(3, 4))

# round
print(round(7.25))

#factorial
print(math.factorial(5))

#floor
print(math.floor(7.25))

#ceiling
print(math.ceil(7.25))

#trunc
print(math.trunc(7.25))

#log
print(math.log(100, 10))

#log10
print(math.log10(1000))

#exponential
print(math.exp(3))

#trigonometric functions

#convert degree to radian
print(math.radians(90))
#convert radian to degree
print(math.degrees(math.pi/2))

#trigonometric sine value
print(math.sin(math.radians(90)))
#trigonometric cosine value
print(math.cos(math.radians(0)))
#trigonometric tangent value
print(math.tan(math.radians(45)))

#Constant value
print(math.pi)
# Euler's number
print(math.e)
#infinity
print(math.inf)
#not a number
print(math.nan)
